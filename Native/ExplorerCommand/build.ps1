. (Join-Path $PSScriptRoot '../Toolchain.ps1')
$toolchain = Get-OfficialToolchain
$msvcRoot = $toolchain.MsvcRoot
$sdkRoot = $toolchain.SdkRoot
$sdkVersion = $toolchain.SdkVersion
$hostBin = $toolchain.HostBin
$env:Path = "$hostBin;$env:Path"

New-Item -ItemType Directory -Force $OutputDirectory | Out-Null
$OutputDirectory = (Resolve-Path -LiteralPath $OutputDirectory).Path
$object = Join-Path $OutputDirectory 'ExplorerCommand.obj'
$dll = Join-Path $OutputDirectory 'LEExplorerCommand.dll'

function Invoke-Native {
    param([string]$File, [string[]]$Arguments)
    & $File @Arguments 2>&1 | ForEach-Object { Write-Host $_ }
    if ($LASTEXITCODE -ne 0) {
        throw "命令失败（$LASTEXITCODE）：$File $($Arguments -join ' ')"
    }
}

# Menu wording has one source: the classic menu's Strings*.resx. Generate the native table from it so
# every translated culture is covered and the two menus cannot drift apart.
function ConvertTo-WideLiteral {
    param([string]$Text)
    $builder = [System.Text.StringBuilder]::new('L"')
    foreach ($character in $Text.ToCharArray()) {
        $code = [int]$character
        if ($character -eq '"' -or $character -eq '\') {
            [void]$builder.Append('\').Append($character)
        }
        elseif ($code -ge 0x20 -and $code -lt 0x7F) {
            [void]$builder.Append($character)
        }
        else {
            # A \x escape would absorb following hex digits: end the literal and start a new one.
            [void]$builder.AppendFormat('\x{0:x4}', $code).Append('" L"')
        }
    }
    return $builder.Append('"').ToString()
}

# The resource keys, in the field order of the native Texts struct in ExplorerCommand.cpp.
$menuKeys = 'Submenu', 'RunDefault', 'ManageApp', 'ManageAll'

function Get-MenuTexts {
    param([string]$ResxPath, [hashtable]$Fallback)
    $values = @{}
    foreach ($node in ([xml](Get-Content -LiteralPath $ResxPath -Raw -Encoding UTF8)).root.data) {
        $values[$node.name] = $node.value
    }
    foreach ($key in $menuKeys) {
        if (-not $values.ContainsKey($key)) {
            if ($null -eq $Fallback) { throw "$ResxPath 缺少 $key。" }
            $values[$key] = $Fallback[$key]
        }
    }
    return $values
}

function Format-MenuTexts {
    param([hashtable]$Texts)
    return '{' + (($menuKeys | ForEach-Object { ConvertTo-WideLiteral $Texts[$_] }) -join ', ') + '}'
}

$menuResources = Join-Path $PSScriptRoot '..\..\LEContextMenuHandler'
$neutralTexts = Get-MenuTexts (Join-Path $menuResources 'Strings.resx') $null
$generatedDirectory = Join-Path $OutputDirectory 'generated'
New-Item -ItemType Directory -Force $generatedDirectory | Out-Null
# ModernMenu.ps1 finds the registered package by name; a renamed manifest identity would make its
# Unregister and stale-package removal silently match nothing.
$manifestIdentity = ([xml](Get-Content -LiteralPath (Join-Path $PSScriptRoot 'AppxManifest.xml') -Raw -Encoding UTF8)).Package.Identity.Name
$scriptText = Get-Content -LiteralPath (Join-Path $PSScriptRoot '../../Scripts/ModernMenu.ps1') -Raw -Encoding UTF8
$scriptPackageName = [regex]::Match($scriptText, '\$packageName\s*=\s*''([^'']+)''').Groups[1].Value
if ($manifestIdentity -ne $scriptPackageName) {
    throw "AppxManifest.xml 的包标识名（$manifestIdentity）与 ModernMenu.ps1 的 `$packageName（$scriptPackageName）不一致。"
}

# The class id is written once, in AppxManifest.xml (the verb and the COM class must name the same id).
$manifestText = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'AppxManifest.xml') -Raw -Encoding UTF8
$classIds = @([regex]::Matches($manifestText, '(?:Clsid|Class Id)="([0-9A-Fa-f-]{36})"') | ForEach-Object { $_.Groups[1].Value.ToUpperInvariant() } | Select-Object -Unique)
if ($classIds.Count -ne 1) {
    throw "AppxManifest.xml 中的 Verb Clsid 与 COM Class Id 必须是同一个 GUID，实际为：$($classIds -join ', ')"
}
$guid = [guid]$classIds[0]
$guidBytes = $guid.ToByteArray()
$tail = (8..15 | ForEach-Object { '0x{0:x2}' -f $guidBytes[$_] }) -join ', '
$clsidInitializer = ('{{0x{0:x8}, 0x{1:x4}, 0x{2:x4}, {{' -f [BitConverter]::ToUInt32($guidBytes, 0), [BitConverter]::ToUInt16($guidBytes, 4), [BitConverter]::ToUInt16($guidBytes, 6)) + $tail + '}}'
$lines = @('// Generated by build.ps1 from AppxManifest.xml and LEContextMenuHandler/Strings*.resx. Do not edit.',
    "static const CLSID CLSID_LERunCommand = $clsidInitializer;",
    "static const Texts kNeutralTexts = $(Format-MenuTexts $neutralTexts);",
    'static const LocalizedTexts kLocalizedTexts[] = {')
foreach ($file in Get-ChildItem -LiteralPath $menuResources -Filter 'Strings.*.resx' | Sort-Object Name) {
    $culture = $file.BaseName.Substring('Strings.'.Length)
    $lines += "    {L`"$culture`", $(Format-MenuTexts (Get-MenuTexts $file.FullName $neutralTexts))},"
}
$lines += '};'
Set-Content -LiteralPath (Join-Path $generatedDirectory 'MenuTexts.h') -Value $lines -Encoding utf8

Invoke-Native (Join-Path $hostBin 'cl.exe') @(
    '/nologo', '/utf-8', '/c', '/O2', '/MT', '/GS', '/guard:cf', '/GR-', '/EHs-c-', '/W4', '/WX',
    '/Zc:wchar_t', '/DUNICODE', '/D_UNICODE', '/DWIN32_LEAN_AND_MEAN', '/DNDEBUG',
    "/I$generatedDirectory",
    "/I$(Join-Path $msvcRoot 'include')",
    "/I$(Join-Path $sdkRoot "Include\$sdkVersion\ucrt")",
    "/I$(Join-Path $sdkRoot "Include\$sdkVersion\shared")",
    "/I$(Join-Path $sdkRoot "Include\$sdkVersion\um")",
    "/Fo$object", (Join-Path $PSScriptRoot 'ExplorerCommand.cpp'))

Invoke-Native (Join-Path $hostBin 'link.exe') @(
    '/nologo', '/dll', '/machine:x64', '/debug:none', '/opt:ref', '/opt:icf',
    '/dynamicbase', '/highentropyva', '/nxcompat', '/guard:cf', '/CETCOMPAT', '/manifest:no',
    "/def:$(Join-Path $PSScriptRoot 'ExplorerCommand.def')", "/out:$dll",
    "/libpath:$(Join-Path $sdkRoot "Lib\$sdkVersion\um\x64")",
    "/libpath:$(Join-Path $sdkRoot "Lib\$sdkVersion\ucrt\x64")",
    "/libpath:$(Join-Path $msvcRoot 'lib\x64')",
    $object, 'kernel32.lib', 'user32.lib', 'ole32.lib', 'shell32.lib', 'shlwapi.lib', 'xmllite.lib')

Write-Host "LEExplorerCommand.dll 已生成：$dll"

# Validate the sparse-package manifest against the real Appx schema. Registration cannot be exercised
# in every environment (it needs Developer Mode or a signed package), but schema errors such as a
# missing capability are caught here. /nv skips payload checks: the files live in the external location.
$makeappx = Join-Path $sdkRoot "bin\$sdkVersion\x64\makeappx.exe"
if (-not (Test-Path -LiteralPath $makeappx)) {
    throw "未找到 makeappx.exe：$makeappx"
}
$validation = Join-Path $OutputDirectory 'manifest-validation'
Remove-Item -LiteralPath $validation -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force $validation | Out-Null
try {
    Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'AppxManifest.xml') -Destination $validation
    Invoke-Native $makeappx @('pack', '/nv', '/o', '/d', $validation, '/p', (Join-Path $OutputDirectory 'manifest-validation.msix'))
}
finally {
    Remove-Item -LiteralPath $validation, (Join-Path $OutputDirectory 'manifest-validation.msix') -Recurse -Force -ErrorAction SilentlyContinue
}
Write-Host 'AppxManifest.xml 通过 Appx 架构校验。'
